const assert=require('node:assert/strict');
const map=require('../dist/map.json');
const terrain=require('../dist/terrain.json');
const api=require('../dist/terrain-relief.js');
const layer=api.prepare(map,terrain);
assert(layer,'Verified SRTM terrain must match the existing OSM projection');
assert.equal(layer.values.length,165,'The imported grid has 165 independently sampled SRTM locations');
assert.equal(terrain.source.dataset.startsWith('NASA SRTMGL1'),true);
assert.equal(layer.min,130);assert.equal(layer.max,193);
assert.equal(layer.sample(0,0),terrain.values[8*11+5],'At a grid node there must be no interpolated invention');
assert.equal(layer.sample(900,0),null,'Unknown area must not show a made-up elevation');
assert.equal(layer.sample(0,-1400),null,'Out-of-bounds samples should stay unknown');
assert(layer.contours.length>20,'Real contour geometry should exist in the inspected area');
assert(layer.contours.every(s=>s.level%10===0&&s.level>=130&&s.level<=200));
assert(layer.contours.every(s=>[s.from.x,s.from.y,s.to.x,s.to.y].every(Number.isFinite)));
assert.equal(api.prepare({...map,projection:{...map.projection,originLat:0}},terrain),null,'Do not project elevations onto a changed map origin');
assert.equal(api.prepare(map,{...terrain,values:terrain.values.slice(1)}),null,'Incomplete terrain samples are rejected');
let calls=0;
const c={save(){},restore(){},beginPath(){},moveTo(){},lineTo(){},stroke(){calls++;},fillRect(){calls++;},fillText(){calls++;},createRadialGradient(){return{addColorStop(){}};}};
api.draw(c,layer,{left:-140,right:140,top:-140,bottom:140},2.3);
assert(calls>0,'Contours paint a visible layer around the market without moving streets');
console.log('Terrain V2.22: 165 SRTM samples, 10m approximate contours, no invented altitudes, bounded rendering OK.');
