const assert=require('node:assert/strict');
const letters=require('../dist/bia-letters.js');

const s=letters.fresh();
assert.equal(letters.next(s),'arrival');
assert.equal(letters.openNotebook(s),false,'no interaction before meeting');
assert.equal(letters.arrive(s),true);
assert.equal(letters.arrive(s),false,'arrival is unique');
assert.equal(letters.meet(s),true);
assert.equal(letters.next(s),'open');
assert.equal(letters.chooseTheme(s,'planos'),false,'paper must be prepared');
assert.equal(letters.openNotebook(s),true);
assert.equal(letters.next(s),'theme');
assert.equal(letters.seal(s),false,'letter needs a theme');
assert.equal(letters.chooseTheme(s,'unknown'),false);
assert.equal(letters.chooseTheme(s,'planos'),true);
assert.equal(letters.next(s),'seal');
const partial=letters.restore(JSON.parse(JSON.stringify(s)));
assert.equal(partial.theme,'planos','partial writing resumes after reload');
assert.equal(partial.sealed,false);
assert.equal(letters.seal(partial),true);
assert.equal(letters.chooseTheme(partial,'retorno'),false,'sealed letters cannot be rewritten');
assert.equal(letters.next(partial),'thank');
assert.equal(letters.claim(partial),true);
assert.equal(letters.claim(partial),false,'one album memory, not one per click');
assert.equal(letters.progress(partial),3);
assert.equal(letters.next(partial),'next');
assert.deepEqual(letters.restore(JSON.parse(JSON.stringify(partial))),partial);
assert.deepEqual(letters.restore(undefined),letters.fresh(),'V2.15 save without letters migrates');
const malformed=letters.restore({arrived:false,talked:true,opened:true,theme:'planos',sealed:true,claimed:true});
assert.deepEqual(malformed,letters.fresh(),'bad save cannot skip meeting');
assert.equal(letters.restore({arrived:true,talked:true,opened:true,theme:'fake',sealed:true,claimed:true}).sealed,false);
assert.equal(letters.restore({arrived:true,talked:true,opened:true,theme:'planos',sealed:false,claimed:true}).claimed,false);
for(const memory of letters.THEMES){const branch=letters.fresh();letters.arrive(branch);letters.meet(branch);letters.openNotebook(branch);letters.chooseTheme(branch,memory.id);letters.seal(branch);assert.equal(letters.claim(branch),true);}
console.log('V2.16 Bia: notebook → theme → seal, branches, one-time memory, partial save and V2.15 migration verified.');
