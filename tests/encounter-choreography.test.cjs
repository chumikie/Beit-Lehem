const assert=require('node:assert/strict');
const api=require('../dist/encounter-choreography.js');
const community=require('../dist/street-community.js');
const encounter=require('../dist/street-encounters.js');
const first=community.EVENTS[0];
const frame=t=>api.timeline({minute:first.start+first.approach+t*first.visit},{...first,phase:'visit'});
assert.equal(frame(.04).stage,'hello');
assert.equal(frame(.23).stage,'listen');
assert.equal(frame(.40).stage,'offer');
assert.equal(frame(.56).stage,'exchange');
assert.equal(frame(.76).stage,'delight');
assert.equal(frame(.95).stage,'farewell');
assert.equal(frame(1).stage,'farewell','The final frame must not jump back to the first greeting');
assert.equal(api.timeline({minute:first.start+first.approach},{...first,phase:'approach'}),null);
const people=[{id:'damiao',x:10,y:15,walking:false},{id:'cica',x:45,y:15,walking:false}];
const state=api.apply(people,{minute:first.start+first.approach+first.visit*.6},{...first,phase:'visit'});
assert(state);
assert.equal(people[0].social.pose,'receive');assert.equal(people[1].social.pose,'offer');
assert.equal(people[0].social.facing,1);assert.equal(people[1].social.facing,-1);
const a=api.tokenPoint({...state,exchange:0},people[0],people[1]);
const b=api.tokenPoint({...state,exchange:1},people[0],people[1]);
assert(a.x>b.x,'The ribbon moves from Ciça towards Damião rather than remaining a floating static icon');
assert.equal(api.token(first),'🎀');
assert.equal(api.token(community.EVENTS.find(e=>e.id==='recado-da-feira')),'✉️');
assert(encounter.EVENTS.length>=3,'Original protagonist encounters remain available');
assert.equal(community.EVENTS.length,5,'All five established community scenes remain');
const absent=[{id:'damiao',x:10,y:15}];
assert.equal(api.apply(absent,{minute:500},{...first,phase:'visit'}),null,'No floating gift with an absent character');
console.log('Choreography V2.22: greeting → listening → handoff → delight → farewell, facing, gift travel and intact itineraries OK.');
