const assert=require('node:assert/strict');
const moments=require('../dist/daily-moments.js');
const world=require('../dist/living-world.js');
const state=world.fresh();
assert.equal(moments.current(state).id,'manha');
assert.equal(moments.nextWindowMinutes(state),12*60-state.minute);
const seen=[];
assert.equal(moments.record(seen,'manha'),true);
assert.equal(moments.record(seen,'manha'),false,'repeat visits should not farm memories');
assert.equal(moments.record(seen,'inventado'),false,'unknown memory must be rejected');
world.advance(state,moments.nextWindowMinutes(state));
assert.equal(moments.current(state).id,'tarde');
assert.equal(moments.record(seen,'tarde'),true);
world.advance(state,moments.nextWindowMinutes(state));
assert.equal(moments.current(state).id,'entardecer');
assert.equal(moments.record(seen,'entardecer'),true);
assert.equal(moments.progress(seen),3);
world.advance(state,moments.nextWindowMinutes(state));
assert.equal(state.day,2);
assert.equal(moments.current(state).id,'manha');
assert.deepEqual(moments.restore(['entardecer','entardecer','foo','manha']),['entardecer','manha']);
console.log('V2.12: three fictional hours, skip schedule, one-time souvenir and save sanitization verified.');
