const assert=require('node:assert/strict');
require('../gemini-modules/secondary-neighbors.js');
const api=global.RoncadorSecondaryNeighbors;
const mila=api.RESIDENTS.find(p=>p.id==='mila');
const rosa=api.RESIDENTS.find(p=>p.id==='rosa');
const clock=(day,minute)=>({day,minute});
const walk=(day,minute,duty=api.agenda(clock(day,minute),mila))=>api.smallWalk(clock(day,minute),mila,duty);
assert.equal(walk(1,16*60+19),null,'No errand before its scheduled window');
assert.equal(walk(2,16*60+25),null,'Not every day has an errand');
assert.equal(walk(1,16*60+36),null,'Errand finishes within its window');
assert.equal(api.smallWalk(clock(1,16*60+25),rosa,api.agenda(clock(1,16*60+25),rosa)),null);
assert.equal(walk(1,16*60+26,{present:true,meeting:true}),null,'Existing meetings take precedence');
const start=walk(1,16*60+20),mid=walk(1,16*60+23),pause=walk(1,16*60+27),returning=walk(1,16*60+32),end=walk(1,16*60+35.999);
assert.equal(start.offset,0);
assert(mid.offset>0&&mid.offset<72);
assert.equal(pause.offset,72);
assert.equal(pause.paused,true);
assert(returning.offset<72&&returning.offset>0);
assert(end.offset>=0&&end.offset<1);
assert.equal(walk(1,16*60+27).offset,pause.offset,'Same day and time reproduce the same errand');
const oldSave=api.restore({seen:['mila'],lastHelp:{mila:1},choices:{mila:'cores'}});
assert.deepEqual(Object.keys(oldSave).sort(),['choices','lastHelp','seen'],'No extra save field');
assert.equal(api.smallWalk(clock(1,16*60+27),mila,api.agenda(clock(1,16*60+27),mila)).paused,true);
console.log('Mila: deterministic short walk, observation, return, priority and legacy saves OK.');
