const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const catalog=JSON.parse(read('drafts/referencias-locais-2026-10-31/catalogo-candidato.json'));
assert(catalog.places.every(p=>p.enabled===false));
assert(catalog.roadProposals.every(p=>p.enabled===false));
const house=catalog.places.find(p=>p.id==='casa_varanda');
assert.equal(house.candidateLocalPoint,null,'Fictional home must not retain a private household coordinate');
const archivePath='references/gemini-2026-10-31/experimento-anonimizado.html.txt';
const archive=read(archivePath);
assert(archive.startsWith('<!-- ARQUIVO DE REFERÊNCIA'));
assert(!/https?:\/\/(?:mail|photos)\.google\.com/i.test(archive),'Private inbox and album links must not enter the source archive');
const mapText=archive.match(/<script[^>]*id="embedded-map-data"[^>]*>([\s\S]*?)<\/script>/);
assert(mapText,'The large archive must preserve its embedded map');
const map=JSON.parse(mapText[1]);
const base=JSON.parse(read('dist/map.json'));
assert.deepEqual(map.roads.map(r=>r.p),base.roads.map(r=>r.p),'Archive anonymization must preserve the public road geometry');
assert.deepEqual(map.bounds,base.bounds);
assert(!map.points.some(p=>p.tags?.building==='house'),'The added private home marker must be omitted');
assert(!map.landmarks.some(p=>p.id==='casa_varanda'),'Fictional home must not retain the original location under a new name');
const oldIds=new Set(base.landmarks.map(p=>p.id));
assert(map.landmarks.filter(p=>!oldIds.has(p.id)).every(p=>p.positionStatus==='user_reference_unverified'));
const entry=read('dist/index.html'),game=read('dist/game.js');
assert(!entry.includes('references/gemini-2026-10-31'));
assert(!game.includes('catalogo-candidato.json'),'Draft catalog must not silently enable unfinished references');
console.log('Reference catalog: disabled candidates, no home marker/private source links, preserved road geometry and isolated archive verified.');
