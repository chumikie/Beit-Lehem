const assert=require('node:assert/strict');
const {create}=require('../dist/street-greetings.js');
const {buildGraph}=require('../dist/pathfinding.js');
const motion=require('../dist/resident-motion.js');
const graph=buildGraph([{p:[[0,0],[120,0]]}]);
const clock={day:2,minute:600};
const pair=()=>[{id:'damiao',x:0,y:0,walking:true},{id:'cica',x:35,y:0,walking:true}];
const greetings=create(graph);
let people=pair();assert.equal(greetings.apply(people,1,clock).length,2,'known friends greet on a shared road without a quest');
assert.equal(people[0].social.pose,'listen','first stop and look');
people=pair();greetings.apply(people,2.5,clock);assert.equal(people[0].social.pose,'wave');assert(people[0].social.intensity>.9);
people=pair();assert.equal(greetings.apply(people,5,clock).length,0,'release both walkers');
assert.equal(greetings.apply(pair(),6,clock).length,0,'cooldown avoids repeated greetings every frame');
assert.equal(create(graph).apply(pair().map(p=>({...p,meeting:true})),1,clock).length,0,'scheduled visits take priority');
assert.equal(create(graph).apply(pair().map(p=>({...p,arriving:true})),1,clock).length,0,'do not interrupt arrivals');
assert.equal(create(graph).apply([{id:'damiao',x:0,y:0},{id:'nara',x:35,y:0}],1,clock).length,0,'no invented friendship');
assert.equal(create({route:()=>({distance:180})}).apply(pair(),1,clock).length,0,'no greeting through a block');
assert.equal(create(graph).apply(pair(),1,{...clock,minute:1300}).length,0,'night stays quiet');
const interrupted=create(graph);interrupted.apply(pair(),1,clock);
assert.equal(interrupted.apply(pair().map(p=>({...p,travel:true})),2,clock).length,0,'agenda interrupts ambient greetings');
// A drifting itinerary must not pull friends out of a held greeting.
for(const hz of [20,30,60]){
 const m=motion.create(graph);m.resolve({id:'cica',x:0,y:0,walking:true},0,1);m.hold(['cica']);
 let held;
 for(let i=1;i<=hz*3;i++)held=m.resolve({id:'cica',x:35,y:0,walking:true},i/hz,1);
 assert.equal(held.x,0,'hold must precede route catch-up');
 m.hold([]);const next=m.resolve({id:'cica',x:35,y:0,walking:true},3+1/hz,1);
 assert(next.x>0&&next.x<5,'release resumes along the original road');
}
console.log('Spontaneous greetings: proximity, established ties, road separation, cooldown, schedule priority and 20/30/60 FPS hold/release OK');
const view=motion.create(graph);
view.resolve({id:'cica',x:0,y:0},1,1);
const walker={id:'cica',walking:true,heading:0,walkBlend:1};
view.present(walker,1,false);
const previous=walker.gaze;
const turned={id:'cica',walking:false,social:{facing:-1}};
view.present(turned,1.016,false);
assert(turned.gaze<previous&&turned.gaze>-.65,'gaze eases toward a friend rather than snapping');
view.present(turned,1.032,true);
assert.equal(turned.gaze,-.65,'reduced motion uses a stable direct gaze');
const actor={id:'cica',x:10,y:0,walking:true};
const frame=view.resolve(actor,1.05,1),readAgain=view.resolve(actor,1.05,1);
assert.equal(readAgain.travelDistance,frame.travelDistance,'repeat state reads cannot stop the visual gait');
