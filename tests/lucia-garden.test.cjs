'use strict';
const assert=require('node:assert/strict');
const garden=require('../dist/lucia-garden.js');
const s=garden.fresh();
assert.deepEqual(s,{arrived:false,talked:false,work:[],memory:null,claimed:false});
assert.equal(garden.next(s),'arrival');
assert.equal(garden.doWork(s,'terra'),false,'cannot garden before talking to Lúcia');
assert.equal(garden.chooseMemory(s,'quintal'),false,'memory requires gardening');
assert.equal(garden.claim(s),false,'reward cannot be claimed early');
assert.equal(garden.arrive(s),true);
assert.equal(garden.arrive(s),false,'arrival only counts once');
assert.equal(garden.next(s),'talk');
assert.equal(garden.meet(s),true);
assert.equal(garden.meet(s),false,'conversation only counts once');
assert.equal(garden.next(s),'work');
assert.equal(garden.doWork(s,'agua'),false,'watering before planting is blocked');
assert.equal(garden.doWork(s,'muda'),false,'planting before loosening soil is blocked');
assert.equal(garden.doWork(s,'terra'),true);
assert.equal(garden.doWork(s,'terra'),false,'same garden task cannot be duplicated');
assert.deepEqual(garden.restore(JSON.parse(JSON.stringify(s))),s,'unfinished soil preparation survives save/reload');
assert.equal(garden.doWork(s,'muda'),true);
assert.equal(garden.doWork(s,'agua'),true);
assert.equal(garden.next(s),'memory');
assert.equal(garden.ready(s),false,'finishing gestures alone does not claim reward');
assert.equal(garden.chooseMemory(s,'not-a-choice'),false,'invalid choices do not save');
assert.equal(garden.chooseMemory(s,'conversa'),true);
assert.equal(garden.next(s),'thank');
assert.equal(garden.ready(s),true);
assert.equal(garden.claim(s),true);
assert.equal(garden.claim(s),false,'reward cannot be duplicated');
assert.equal(garden.chooseMemory(s,'chuva'),false,'the remembered choice is locked after claim');
assert.equal(garden.next(s),'next');
assert.equal(garden.progress(s),3);
assert.deepEqual(garden.restore(JSON.parse(JSON.stringify(s))),s,'completed reward and choice survive reload');
assert.deepEqual(garden.restore(undefined),garden.fresh(),'V2.14 saves with no Lúcia field remain valid');
assert.deepEqual(garden.restore({arrived:false,talked:true,work:['terra','muda','agua'],memory:'conversa',claimed:true}),garden.fresh(),'inconsistent saves do not claim rewards');
assert.deepEqual(garden.restore({arrived:true,talked:true,work:['agua','terra','muda'],memory:'chuva',claimed:true}),{arrived:true,talked:true,work:[],memory:null,claimed:false},'out-of-order imported work is rejected');
const mid=garden.restore({arrived:true,talked:true,work:['terra','muda'],memory:'quintal',claimed:true});
assert.deepEqual(mid,{arrived:true,talked:true,work:['terra','muda'],memory:null,claimed:false},'no reward from unfinished garden');
console.log('V2.15 Lúcia: ordered gardening, choice, unique reward, partial reload, corruption checks and V2.14 save migration OK.');
