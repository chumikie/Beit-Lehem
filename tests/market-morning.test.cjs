'use strict';
const assert=require('node:assert/strict');
const m=require('../dist/market-morning.js');
const chapter=m.fresh();
assert.deepEqual(chapter,{arrived:false,talked:false,work:[],claimed:false});
assert.equal(m.next(chapter),'arrival');
assert.equal(m.doWork(chapter,'frutas'),false,'cannot work before meeting Damião');
assert.equal(m.claim(chapter),false,'cannot claim early');
assert.equal(m.arrive(chapter),true);
assert.equal(m.arrive(chapter),false,'arrival counts once');
assert.equal(m.next(chapter),'talk');
assert.equal(m.progress(chapter),1);
assert.equal(m.meet(chapter),true);
assert.equal(m.meet(chapter),false,'conversation counts once');
assert.equal(m.next(chapter),'work');
assert.equal(m.doWork(chapter,'falso'),false,'invalid action is ignored');
assert.equal(m.doWork(chapter,'toldo'),true);
assert.equal(m.doWork(chapter,'toldo'),false,'no double count on repeated tap');
assert.equal(m.doWork(chapter,'frutas'),true);
assert.equal(m.ready(chapter),false);
const mid=m.restore(JSON.parse(JSON.stringify(chapter)));
assert.deepEqual(mid.work,['toldo','frutas'],'incomplete work resumes in its exact state');
assert.equal(m.next(mid),'work');
assert.equal(m.doWork(mid,'cestos'),true);
assert.equal(m.next(mid),'thank');
assert.equal(m.claim(mid),true);
assert.equal(m.claim(mid),false,'reward is only claimed once');
assert.equal(m.doWork(mid,'cestos'),false);
assert.equal(m.progress(mid),3);
assert.equal(m.next(mid),'next');
assert.deepEqual(m.restore(JSON.parse(JSON.stringify(mid))),mid,'reward survives reload');
assert.deepEqual(m.restore(undefined),m.fresh(),'V2.13 saves without new field are migrated safely');
assert.deepEqual(m.restore({arrived:false,talked:true,work:['toldo','frutas','cestos'],claimed:true}),m.fresh(),'invalid completion does not bypass introduction');
assert.deepEqual(m.restore({arrived:true,talked:true,work:['toldo','toldo','fake','cestos'],claimed:true}),{arrived:true,talked:true,work:['toldo','cestos'],claimed:false},'malformed save has deduplicated work and no premature reward');
assert.equal(m.meet(m.fresh()),true,'meeting implies arrival if player directly approaches Damião');
console.log('V2.14 Mercado: arrival, contextual meeting, 3 tasks, idempotent reward, reload and V2.13 migration OK.');
