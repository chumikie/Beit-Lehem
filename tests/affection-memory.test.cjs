const assert=require('node:assert/strict');
const affection=require('../dist/affection-memory.js');
const base={living:{day:1,minute:8*60+30,people:{damiao:{bond:0,fatigue:18},lucia:{bond:0},bia:{bond:0}}},sideNeighbors:{seen:[],choices:{}},communitySeen:[],marketMorning:{claimed:false},luciaGarden:{claimed:false},biaLetters:{claimed:false}};
const look=(id,state=base)=>affection.snapshot(state,id);
assert.equal(look('damiao').remembered,false);
assert.equal(look('damiao').expression,'curious');
assert.equal(look('unlisted'),null);
const friends=structuredClone(base);friends.living.people.damiao.bond=3;
assert.equal(look('damiao',friends).close,true);
assert.match(look('damiao',friends).line,/rever/);
const afterWork=structuredClone(base);afterWork.marketMorning.claimed=true;
assert.match(look('damiao',afterWork).line,/cestos e as frutas/);
assert.equal(look('damiao',afterWork).expression,'warm');
afterWork.communitySeen.push('fitas-de-bom-dia');
assert.match(look('damiao',afterWork).line,/Ciça/);
afterWork.communitySeen.push('recado-da-feira');
assert.match(look('damiao',afterWork).line,/Téo/);
const garden=structuredClone(base);garden.luciaGarden.claimed=true;
assert.match(look('lucia',garden).line,/mudinha/);
garden.communitySeen.push('memorias-do-jardim');
assert.match(look('lucia',garden).line,/Nara/);
const letters=structuredClone(base);letters.biaLetters.claimed=true;
assert.match(look('bia',letters).line,/carta/);
letters.communitySeen.push('caderno-compartilhado');
assert.match(look('bia',letters).line,/Nara/);
letters.communitySeen.push('bilhete-de-volta');
assert.match(look('bia',letters).line,/Téo/);
const cica=structuredClone(base);cica.sideNeighbors.seen.push('cica');cica.sideNeighbors.choices.cica='fitas';
assert.equal(look('cica',cica).remembered,true);
assert.match(look('cica',cica).line,/organizamos as fitas/);
cica.communitySeen.push('fitas-de-bom-dia');
assert.match(look('cica',cica).line,/Damião/);
const nara=structuredClone(base);nara.sideNeighbors.choices.nara='desenho';
assert.match(look('nara',nara).line,/juntos/);
nara.communitySeen.push('caderno-compartilhado');
assert.match(look('nara',nara).line,/Bia/);
const teo=structuredClone(base);teo.sideNeighbors.choices.teo='recado';
assert.match(look('teo',teo).line,/recadinho/);
teo.communitySeen.push('bilhete-de-volta');
assert.match(look('teo',teo).line,/Bia/);
const tired=structuredClone(afterWork);tired.living.people.damiao.fatigue=81;
assert.equal(look('damiao',tired).expression,'sleepy');
assert.equal(base.communitySeen.length,0,'reading memory must not change the save');
assert.deepEqual(Object.keys(base).sort(),['biaLetters','communitySeen','living','luciaGarden','marketMorning','sideNeighbors'].sort(),'no new storage key is needed');
console.log('Affection V2.21: 6 personalities, all 3 chapters, letters, gifts, friendships, smile/energy and legacy-safe derivation OK.');
